export type TarotCopyId = keyof typeof tarotCopy.zh;

export const stageCopy = (lang: Language, stage: number) => [copy[lang].origin, copy[lang].passage, copy[lang].result][stage - 1];
export const stageLabel = (lang: Language, stage: number) => [copy[lang].stageOrigin, copy[lang].stagePassage, copy[lang].stageResult][stage - 1];
export const interpolate = (template: string, values: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''));

export function tarotEntry(lang: Language, id: string) {
  return tarotCopy[lang][id as TarotCopyId];
}

export function tarotName(lang: Language, id: string, fallback = ''): string {
  return tarotEntry(lang, id)?.name ?? fallback;
}

export function tarotKeyword(lang: Language, id: string, orientation: 'upright' | 'reversed', fallback = ''): string {
  const entry = tarotEntry(lang, id);
  if (!entry) return fallback;
  return orientation === 'reversed' ? entry.keywordReversed : entry.keywordUpright;
}

export function tarotEncounter(lang: Language, id: string) {
  return tarotEntry(lang, id)?.encounter;
}

export function tarotEncounterName(lang: Language, id: string, fallback = ''): string {
  return tarotEncounter(lang, id)?.name ?? fallback;
}

export function tarotEncounterPrompt(lang: Language, id: string, fallback = ''): string {
  return tarotEncounter(lang, id)?.prompt ?? fallback;
}

export function tarotGiftReaction(lang: Language, id: string, offered: boolean, fallback = ''): string {
  const encounter = tarotEncounter(lang, id);
  if (!encounter) return fallback;
  return offered ? encounter.giftReactionOffered : encounter.giftReactionKept;
}
